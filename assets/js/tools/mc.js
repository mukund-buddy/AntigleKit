function drawLayerPreview(canvas, points) {
  const ctx = canvas.getContext('2d');
  const dpr = window.devicePixelRatio || 1;
  const w = canvas.clientWidth, h = canvas.clientHeight;
  canvas.width = w * dpr; canvas.height = h * dpr;
  ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
  ctx.clearRect(0, 0, w, h);
  ctx.fillStyle = '#1b1b2f';
  ctx.fillRect(0, 0, w, h);
  if (!points || !points.size) return;
  let mnX = Infinity, mxX = -Infinity, mnY = Infinity, mxY = -Infinity;
  for (const k of points) {
    const [x, y] = k.split(',').map(Number);
    if (x < mnX) mnX = x; if (x > mxX) mxX = x;
    if (y < mnY) mnY = y; if (y > mxY) mxY = y;
  }
  const gw = mxX - mnX + 1, gh = mxY - mnY + 1;
  const cs = Math.max(3, Math.min(16, Math.floor(Math.min((w - 20) / gw, (h - 20) / gh))));
  const ox = (w - gw * cs) / 2, oy = (h - gh * cs) / 2;
  // Grid
  ctx.strokeStyle = 'rgba(80,80,120,0.3)'; ctx.lineWidth = 0.5; ctx.beginPath();
  for (let gx = 0; gx <= gw; gx++) { const px = gx * cs + ox; ctx.moveTo(px, oy); ctx.lineTo(px, oy + gh * cs); }
  for (let gy = 0; gy <= gh; gy++) { const py = gy * cs + oy; ctx.moveTo(ox, py); ctx.lineTo(ox + gw * cs, py); }
  ctx.stroke();
  // Blocks
  for (const k of points) {
    const [x, y] = k.split(',').map(Number);
    const px = (x - mnX) * cs + ox, py = (y - mnY) * cs + oy;
    const pad = Math.max(0.3, cs * 0.08);
    ctx.fillStyle = '#2d8a4e'; ctx.fillRect(px + pad, py + pad, cs - pad * 2, cs - pad * 2);
    ctx.fillStyle = '#4ecb71'; ctx.fillRect(px + pad, py + pad, cs - pad * 2, (cs - pad * 2) * 0.45);
    ctx.strokeStyle = 'rgba(0,0,0,0.5)'; ctx.lineWidth = 0.8;
    ctx.strokeRect(px + pad + 0.5, py + pad + 0.5, cs - pad * 2 - 1, cs - pad * 2 - 1);
  }
}

