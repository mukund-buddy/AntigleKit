/** Circle — returns Set of "x,y" strings. Origin at (0,0). */
function circlePoints(r, filled) {
  const pts = new Set();
  if (r < 0) return pts;
  if (r === 0) { pts.add('0,0'); return pts; }
  if (filled) {
    for (let y = -r; y <= r; y++)
      for (let x = -r; x <= r; x++)
        if (x * x + y * y <= r * r) pts.add(`${x},${y}`);
  } else {
    // Bresenham outline
    let x = r, y = 0, err = 1 - r;
    while (x >= y) {
      for (const s of [1, -1]) for (const t of [1, -1]) {
        pts.add(`${s * x},${t * y}`);
        pts.add(`${s * y},${t * x}`);
      }
      y++;
      if (err < 0) err += 2 * y + 1;
      else { x--; err += 2 * (y - x) + 1; }
    }
  }
  return pts;
}

/** Oval (ellipse) — returns Set of "x,y" strings. Origin at (0,0). */
function ovalPoints(rx, ry, filled) {
  const pts = new Set();
  if (rx <= 0 || ry <= 0) { if (rx >= 0 && ry >= 0) pts.add('0,0'); return pts; }
  if (filled) {
    const rx2 = rx * rx, ry2 = ry * ry;
    for (let y = -ry; y <= ry; y++)
      for (let x = -rx; x <= rx; x++)
        if (x * x / rx2 + y * y / ry2 <= 1) pts.add(`${x},${y}`);
  } else {
    // Parametric ellipse — enough samples for smooth outline
    const steps = Math.max(rx, ry) * 8 + 16;
    for (let i = 0; i < steps; i++) {
      const a = (i / steps) * 2 * Math.PI;
      pts.add(`${Math.round(rx * Math.cos(a))},${Math.round(ry * Math.sin(a))}`);
    }
  }
  return pts;
}

/** Sphere layers — array of { y, points } bottom to top. */
function sphereLayers(r, filled) {
  const d = 2 * r + 1;
  const layers = [];
  for (let y = -r; y <= r; y++) {
    const lr = Math.floor(Math.sqrt(r * r - y * y));
    layers.push({ y: y + r, points: circlePoints(lr, filled) });
  }
  return { width: d, height: d, depth: d, layers };
}

/** Dome layers — top half of sphere. */
function domeLayers(r, filled) {
  const all = sphereLayers(r, filled);
  all.layers = all.layers.slice(Math.floor(all.layers.length / 2));
  all.height = all.layers.length;
  return all;
}

/* ═══════════════════════════════════════════
   NBT ENCODER — Big-Endian (Java .litematic)
   ═══════════════════════════════════════════ */

class NBTWriterBE {
  constructor() { this.buf = []; this.enc = new TextEncoder(); }
  b(v) { this.buf.push(v & 0xff); }
  s(v) { this.buf.push((v >> 8) & 0xff, v & 0xff); }
  i(v) { this.buf.push((v >>> 24) & 0xff, (v >>> 16) & 0xff, (v >>> 8) & 0xff, v & 0xff); }
  l(v) {
    const hi = Math.floor(v / 0x100000000);
    this.i(hi); this.i(v | 0);
  }
  str(s) {
    const bytes = this.enc.encode(s);
    this.s(bytes.length);
    this.buf.push(...bytes);
  }
  tag(type, name, fn) { this.b(type); this.str(name); fn(); }
  end() { this.b(0); }
  toBytes() { return new Uint8Array(this.buf); }
}

/** Build .litematic NBT for Java Edition. */
function buildLitematic(blockMap, sizeX, sizeY, sizeZ) {
  // blockMap: Map<"x,y,z", "minecraft:block">
  const palette = new Map();
  palette.set('minecraft:air', 0);
  let idx = 1;
  const flat = [];
  for (let z = 0; z < sizeZ; z++)
    for (let y = 0; y < sizeY; y++)
      for (let x = 0; x < sizeX; x++) {
        const b = blockMap.get(`${x},${y},${z}`) || 'minecraft:air';
        if (!palette.has(b)) palette.set(b, idx++);
        flat.push(palette.get(b));
      }

  const vol = sizeX * sizeY * sizeZ;
  const bpe = Math.max(2, Math.ceil(Math.log2(palette.size)));
  const longs = Math.ceil((vol * bpe) / 64);
  const stateArr = new Array(longs).fill(0n);
  for (let i = 0; i < vol; i++) {
    const off = BigInt(i * bpe);
    stateArr[Number(off / 64n)] |= BigInt(flat[i]) << (off % 64n);
  }
  const signed = stateArr.map(v => {
    const n = Number(v & 0xFFFFFFFFFFFFFFFFn);
    return n > 0x7FFFFFFFFFFFFFFF ? n - 0x10000000000000000 : n;
  });

  const w = new NBTWriterBE();
  // Root compound
  w.tag(10, 'Root', () => {
    // Metadata
    w.tag(10, 'Metadata', () => {
      w.tag(8, 'Name', () => w.str('Minecraft Circle Blueprint'));
      w.tag(3, 'Volume', () => w.i(vol));
      w.tag(3, 'TotalBlocks', () => w.i(blockMap.size));
      w.tag(8, 'Author', () => w.str('AntigleKit'));
      w.tag(8, 'Description', () => w.str('Generated by AntigleKit MC Circle Generator'));
      w.tag(3, 'RegionCount', () => w.i(1));
      w.tag(3, 'EncodingVersion', () => w.i(1));
      w.tag(3, 'TotalVolume', () => w.i(vol));
      w.end();
    });
    // Regions
    w.tag(10, 'Regions', () => {
      w.tag(10, 'Region', () => {
        // Position: list of 3 ints
        w.tag(9, 'Position', () => { w.b(3); w.i(3); w.i(0); w.i(0); w.i(0); });
        // Size: list of 3 ints
        w.tag(9, 'Size', () => { w.b(3); w.i(3); w.i(sizeX); w.i(sizeY); w.i(sizeZ); });
        // BlockStates: long array
        w.tag(12, 'BlockStates', () => { w.i(signed.length); for (const v of signed) w.l(v); });
        // TileEntities: empty list of compounds
        w.tag(9, 'TileEntities', () => { w.b(10); w.i(0); });
        // Entities: empty list of compounds
        w.tag(9, 'Entities', () => { w.b(10); w.i(0); });
        w.end();
      });
      w.end();
    });
    w.tag(3, 'MinecraftDataVersion', () => w.i(3955));
    w.end();
  });
  return w.toBytes();
}

/* ═══════════════════════════════════════════
   NBT ENCODER — Little-Endian (Bedrock .mcstructure)
   ═══════════════════════════════════════════ */

class NBTWriterLE {
  constructor() { this.buf = []; this.enc = new TextEncoder(); }
  b(v) { this.buf.push(v & 0xff); }
  s(v) { this.buf.push(v & 0xff, (v >> 8) & 0xff); }
  i(v) { this.buf.push(v & 0xff, (v >>> 8) & 0xff, (v >>> 16) & 0xff, (v >>> 24) & 0xff); }
  l(v) { const lo = v | 0, hi = Math.floor(v / 0x100000000); this.i(lo); this.i(hi); }
  str(s) {
    const bytes = this.enc.encode(s);
    this.s(bytes.length);
    this.buf.push(...bytes);
  }
  tag(type, name, fn) { this.b(type); this.str(name); fn(); }
  end() { this.b(0); }
  toBytes() { return new Uint8Array(this.buf); }
}

/** Build .mcstructure for Bedrock Edition — pre-counts non-air blocks. */
function buildMcstructureFixed(blockMap, sizeX, sizeY, sizeZ) {
  const paletteArr = ['minecraft:air'];
  const paletteIdx = { 'minecraft:air': 0 };
  for (const block of blockMap.values()) {
    if (!(block in paletteIdx)) {
      paletteIdx[block] = paletteArr.length;
      paletteArr.push(block);
    }
  }

  // Pre-count non-air blocks
  const nonAir = [];
  for (let z = 0; z < sizeZ; z++)
    for (let y = 0; y < sizeY; y++)
      for (let x = 0; x < sizeX; x++) {
        const b = blockMap.get(`${x},${y},${z}`);
        if (b && b !== 'minecraft:air') nonAir.push({ x, y, z, idx: paletteIdx[b] });
      }

  const w = new NBTWriterLE();
  w.tag(10, '', () => {
    w.tag(1, 'format_version', () => w.b(1));
    w.tag(9, 'size', () => { w.b(3); w.i(3); w.i(sizeX); w.i(sizeY); w.i(sizeZ); });
    w.tag(9, 'blocks', () => {
      w.b(10); w.i(nonAir.length);
      for (const { x, y, z, idx } of nonAir) {
        w.tag(10, '', () => {
          w.tag(3, 'block_index', () => w.i(idx));
          w.tag(9, 'position', () => { w.b(3); w.i(3); w.i(x); w.i(y); w.i(z); });
        });
      }
    });
    w.tag(9, 'palette', () => {
      w.b(10); w.i(paletteArr.length);
      for (const id of paletteArr) {
        w.tag(10, '', () => {
          w.tag(8, 'name', () => w.str(id));
          w.tag(10, 'states', () => {
            w.tag(8, 'version', () => w.str('1.170.0'));
            w.end();
          });
        });
      }
    });
    w.tag(9, 'structure_world_origin', () => { w.b(3); w.i(3); w.i(0); w.i(0); w.i(0); });
    w.end();
  });
  return w.toBytes();
}

